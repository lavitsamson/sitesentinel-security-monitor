import { randomBytes } from 'node:crypto';
import { CheckRunModel, SiteModel, UserModel, type CheckRun } from '@sitesentinel/db';
import {
  CHECK_INTERVAL_MINUTES,
  CHECK_TYPES,
  gradeFor,
  statusFromFindings,
  type Severity,
  type SiteStatus,
} from '@sitesentinel/shared';
import type { PasswordHasher } from '../auth/passwords.js';
import { DEMO_PASSWORD } from './demo-data.js';
import { prng } from './demo-history.js';

export const PERF_EMAIL = 'perf@sitesentinel.demo';
export const PERF_PASSWORD = DEMO_PASSWORD;

/** The milestone 8 target: 2,000 sites and 1M runs, all owned by one user (the worst case). */
export const PERF_DEFAULTS = { sites: 2_000, runsPerSite: 500 } as const;

/** Runs are spread over this window, well inside the 90-day TTL. */
const SPREAD_DAYS = 30;
const DAY_MS = 24 * 60 * 60 * 1000;
const TAGS = ['client-a', 'client-b', 'client-c', 'client-d', 'client-e', 'internal', 'staging'];

export interface PerfSeedOptions {
  sites: number;
  runsPerSite: number;
  /** Runs per insertMany call. */
  batchSize?: number;
  onProgress?: (runsInserted: number) => void;
}

function pick<T>(items: readonly T[], random: () => number): T {
  return items[Math.floor(random() * items.length)] as T;
}

function statusFor(random: () => number): SiteStatus {
  const r = random();
  if (r < 0.9) return 'UP';
  if (r < 0.95) return 'DEGRADED';
  if (r < 0.98) return 'DOWN';
  return 'UNKNOWN';
}

function findingsFor(score: number) {
  const severity: Severity | null = score < 60 ? 'high' : score < 85 ? 'medium' : null;
  return severity
    ? [
        {
          code: 'PERF_SYNTHETIC',
          severity,
          message: 'Synthetic finding (performance dataset).',
          recommendation: 'None: this run was generated by pnpm seed:perf.',
        },
      ]
    : [];
}

/**
 * The performance dataset (CLAUDE.md §14, milestone 8). Every site is paused and
 * labelled demo data, under example.com subdomains, so a running worker never
 * checks any of them. Safe to re-run: only the perf user's data is replaced.
 */
export async function seedPerfData(
  passwords: PasswordHasher,
  { sites: siteCount, runsPerSite, batchSize = 10_000, onProgress }: PerfSeedOptions,
  now = new Date(),
) {
  const existing = await UserModel.findOne({ email: PERF_EMAIL });
  if (existing) {
    await Promise.all([
      SiteModel.deleteMany({ ownerId: existing._id }),
      CheckRunModel.deleteMany({ ownerId: existing._id }),
    ]);
    await existing.deleteOne();
  }
  // Build indexes before the bulk insert, as production would have them.
  await Promise.all([SiteModel.init(), CheckRunModel.init()]);

  const user = await UserModel.create({
    email: PERF_EMAIL,
    name: 'Performance Test',
    passwordHash: await passwords.hash(PERF_PASSWORD),
    emailVerifiedAt: now,
  });

  const random = prng(8);
  const sites = await SiteModel.insertMany(
    Array.from({ length: siteCount }, (_, i) => {
      const number = String(i + 1).padStart(4, '0');
      const score = Math.round(35 + random() * 65);
      return {
        ownerId: user._id,
        domain: `site-${number}.perf.example.com`,
        displayName: `Perf site ${number}`,
        checkIntervalMinutes: pick(CHECK_INTERVAL_MINUTES, random),
        paused: true,
        demo: true,
        tags: random() < 0.8 ? [pick(TAGS, random)] : [],
        currentScore: score,
        currentGrade: gradeFor(score),
        status: statusFor(random),
        lastCheckedAt: new Date(now.getTime() - Math.floor(random() * DAY_MS)),
        verification: { token: randomBytes(16).toString('hex'), verifiedAt: now },
      };
    }),
  );

  let inserted = 0;
  let batch: CheckRun[] = [];
  const flush = async () => {
    if (batch.length === 0) return;
    // The driver directly: mongoose document validation would dominate the run time.
    await CheckRunModel.collection.insertMany(batch, { ordered: false });
    inserted += batch.length;
    batch = [];
    onProgress?.(inserted);
  };

  const step = (SPREAD_DAYS * DAY_MS) / runsPerSite;
  for (const site of sites) {
    const base = site.currentScore ?? 80;
    for (let j = 0; j < runsPerSite; j++) {
      const score = Math.max(0, Math.min(100, Math.round(base + (random() - 0.5) * 30)));
      const findings = findingsFor(score);
      batch.push({
        siteId: site._id,
        ownerId: user._id,
        type: CHECK_TYPES[j % CHECK_TYPES.length] as CheckRun['type'],
        status: statusFromFindings(findings),
        score,
        findings,
        raw: { synthetic: true },
        durationMs: Math.round(80 + random() * 400),
        trigger: 'SCHEDULED',
        startedAt: new Date(now.getTime() - j * step - Math.floor(random() * 60_000)),
      });
      if (batch.length >= batchSize) await flush();
    }
  }
  await flush();

  return { userId: user.id as string, sites: sites.length, runs: inserted };
}
